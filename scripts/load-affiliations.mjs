#!/usr/bin/env node
// Reads docs/Affiliations.csv and emits a TypeScript module exporting the
// list of selectable affiliations (grouped by Type).
//
// Usage:  node scripts/load-affiliations.mjs
// Output: src/lib/affiliations.generated.ts
//
// The CSV lives outside git; the generated .ts file is what actually ships.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '..')

const CSV_PATH = join(repoRoot, 'docs/Affiliations.csv')
const OUT_PATH = join(repoRoot, 'src/lib/affiliations.generated.ts')

// Minimal RFC-4180 CSV parser — handles quoted commas but nothing exotic.
function parseCsv(text) {
  const rows = []
  let field = ''
  let row = []
  let inQuotes = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (inQuotes) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"'
        i++
      } else if (c === '"') {
        inQuotes = false
      } else {
        field += c
      }
    } else if (c === '"') {
      inQuotes = true
    } else if (c === ',') {
      row.push(field)
      field = ''
    } else if (c === '\n') {
      row.push(field)
      rows.push(row)
      row = []
      field = ''
    } else if (c === '\r') {
      // ignore — handled by \n
    } else {
      field += c
    }
  }
  if (field.length || row.length) {
    row.push(field)
    rows.push(row)
  }
  return rows
}

function tsString(s) {
  return "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'"
}

function main() {
  const raw = readFileSync(CSV_PATH, 'utf8')
  const rows = parseCsv(raw)
  const [header, ...data] = rows

  const idx = Object.fromEntries(header.map((h, i) => [h.trim(), i]))
  for (const col of ['Type', 'Affiliation']) {
    if (!(col in idx)) throw new Error(`CSV missing required column: ${col}`)
  }

  const groups = new Map()
  let total = 0
  for (const row of data) {
    if (row.every((c) => !c || !c.trim())) continue
    const type = (row[idx['Type']] ?? '').trim()
    const name = (row[idx['Affiliation']] ?? '').trim()
    if (!type || !name) continue
    if (!groups.has(type)) groups.set(type, [])
    groups.get(type).push(name)
    total++
  }

  const groupLines = []
  for (const [type, names] of groups.entries()) {
    names.sort((a, b) => a.localeCompare(b))
    groupLines.push(
      `  {\n    type: ${tsString(type)},\n    items: [\n${names
        .map((n) => `      ${tsString(n)},`)
        .join('\n')}\n    ],\n  },`
    )
  }

  const contents = `// Auto-generated by scripts/load-affiliations.mjs — do not edit by hand.
// Source: Affiliations.csv (${total} entries, ${groups.size} groups).

export type AffiliationGroup = {
  type: string
  items: string[]
}

export const AFFILIATION_GROUPS: readonly AffiliationGroup[] = [
${groupLines.join('\n')}
] as const

export const ALL_AFFILIATIONS: readonly string[] = AFFILIATION_GROUPS.flatMap(
  (g) => g.items
)
`

  writeFileSync(OUT_PATH, contents)

  console.log(`Wrote ${OUT_PATH}`)
  console.log(`  groups: ${groups.size}`)
  console.log(`  items:  ${total}`)
}

main()
