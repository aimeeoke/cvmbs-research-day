#!/usr/bin/env node
// Reads docs/MGL_Ambassadors.csv and emits a Supabase migration that inserts
// each row into `certifications` as an ambassador cert.
//
// Usage:  node scripts/load-mgl-ambassadors.mjs
// Output: supabase/migrations/2026-09-30_load_mgl_ambassadors.sql
//
// The MGL CSV only ships first + last name (no email). So these rows have
// no email — matching to a coauthor on an abstract requires human review
// (name-only identity). The 2026-09-30_certifications_name_only.sql
// migration relaxes the identity CHECK to allow this shape.
//
// The generated SQL is idempotent PER ROW: it only inserts rows that don't
// already exist by (kind='ambassador', source='csv_import', LOWER(first),
// LOWER(last)). Safe to re-run when the CSV grows.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '..')

const CSV_PATH = join(repoRoot, 'docs/MGL_Ambassadors.csv')
const OUT_PATH = join(
  repoRoot,
  'supabase/migrations/2026-09-30_load_mgl_ambassadors.sql'
)

// Minimal RFC-4180 CSV parser — handles quoted commas but nothing exotic.
function parseCsv(text) {
  const rows = []
  let field = ''
  let row = []
  let inQuotes = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (inQuotes) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"'
        i++
      } else if (c === '"') {
        inQuotes = false
      } else {
        field += c
      }
    } else if (c === '"') {
      inQuotes = true
    } else if (c === ',') {
      row.push(field)
      field = ''
    } else if (c === '\n') {
      row.push(field)
      rows.push(row)
      row = []
      field = ''
    } else if (c === '\r') {
      // ignore — handled by \n
    } else {
      field += c
    }
  }
  if (field.length || row.length) {
    row.push(field)
    rows.push(row)
  }
  return rows
}

// Same normalization used in load-faculty.mjs: uppercase first letter of
// each segment (split on space/hyphen/'), leave rest untouched. Preserves
// mixed case ("McCue", "MacDonald", "O'Brien") while fixing all-lowercase
// entries. If the CSV is well-formed, this is effectively a no-op.
function normalizeName(name) {
  return name
    .trim()
    .replace(/\s+/g, ' ')
    .split(/([-\s'])/)
    .map((seg) => (seg.length && /[a-z]/.test(seg[0]) ? seg[0].toUpperCase() + seg.slice(1) : seg))
    .join('')
}

function sqlString(s) {
  return "'" + String(s).replace(/'/g, "''") + "'"
}

function stripBom(s) {
  return s.charCodeAt(0) === 0xfeff ? s.slice(1) : s
}

function main() {
  const raw = readFileSync(CSV_PATH, 'utf8')
  const rows = parseCsv(raw)
  const [headerRaw, ...data] = rows
  const header = headerRaw.map((h) => stripBom(h).trim())

  const idx = Object.fromEntries(header.map((h, i) => [h, i]))
  const required = ['First Name', 'Last Name']
  for (const col of required) {
    if (!(col in idx)) throw new Error(`CSV missing required column: ${col}`)
  }

  const skipped = []
  const ready = []
  const seen = new Set()

  for (const row of data) {
    if (row.every((c) => !c || !c.trim())) continue // blank line
    const first = normalizeName(row[idx['First Name']] ?? '')
    const last = normalizeName(row[idx['Last Name']] ?? '')

    if (!first || !last) {
      skipped.push({ reason: 'missing name', row })
      continue
    }
    const dedupe = `${first.toLowerCase()}|${last.toLowerCase()}`
    if (seen.has(dedupe)) {
      skipped.push({ reason: 'duplicate within CSV', row: `${first} ${last}` })
      continue
    }
    seen.add(dedupe)
    ready.push({ first, last })
  }

  const valueRows = ready
    .map(({ first, last }) => `  (${sqlString(first)}, ${sqlString(last)})`)
    .join(',\n')

  const sql = `-- MGL ambassadors load — generated by scripts/load-mgl-ambassadors.mjs
-- Source: docs/MGL_Ambassadors.csv (${ready.length} rows loaded, ${skipped.length} skipped).
--
-- Idempotent per row: only inserts (first, last) pairs that aren't already
-- present as source='csv_import' ambassador certs. Safe to re-run when
-- the CSV grows.
--
-- All rows land with source='csv_import' and verified_at=NOW() — the CSV
-- from the certifying body IS the verified list. No PDF file (storage_path
-- stays NULL). No email (the CSV doesn't ship any) — identity is name-only.

INSERT INTO certifications (kind, first_name, last_name, source, verified_at)
SELECT 'ambassador', v.first_name, v.last_name, 'csv_import', NOW()
FROM (VALUES
${valueRows}
) AS v(first_name, last_name)
WHERE NOT EXISTS (
  SELECT 1 FROM certifications c
  WHERE c.kind = 'ambassador'
    AND c.source = 'csv_import'
    AND LOWER(c.first_name) = LOWER(v.first_name)
    AND LOWER(c.last_name)  = LOWER(v.last_name)
);
`

  writeFileSync(OUT_PATH, sql)

  console.log(`Wrote ${OUT_PATH}`)
  console.log(`  loaded:  ${ready.length}`)
  console.log(`  skipped: ${skipped.length}`)
  if (skipped.length) {
    console.log('  skipped rows:')
    for (const s of skipped) {
      console.log(`    - [${s.reason}] ${typeof s.row === 'string' ? s.row : JSON.stringify(s.row)}`)
    }
  }
}

main()
